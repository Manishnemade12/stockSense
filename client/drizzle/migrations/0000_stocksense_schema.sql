CREATE TYPE public.app_role AS ENUM ('INVENTORY_MANAGER','WAREHOUSE_STAFF');
CREATE TYPE public.operation_type AS ENUM ('RECEIPT','DELIVERY','INTERNAL_TRANSFER','ADJUSTMENT');
CREATE TYPE public.operation_status AS ENUM ('DRAFT','WAITING','READY','DONE','CANCELED');
CREATE TYPE public.partner_type AS ENUM ('SUPPLIER','CUSTOMER');
CREATE TYPE public.location_type AS ENUM ('INTERNAL','VENDOR','CUSTOMER','ADJUSTMENT_VIRTUAL');

CREATE TABLE public.warehouses (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(120) NOT NULL,
  code varchar(20) NOT NULL UNIQUE,
  address text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.locations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  warehouse_id bigint REFERENCES public.warehouses(id),
  parent_location_id bigint REFERENCES public.locations(id),
  name varchar(120) NOT NULL,
  code varchar(30) NOT NULL,
  location_type public.location_type NOT NULL DEFAULT 'INTERNAL',
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.product_categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL,
  parent_category_id bigint REFERENCES public.product_categories(id),
  is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE public.units_of_measure (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(40) NOT NULL,
  code varchar(10) NOT NULL,
  is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE public.products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(150) NOT NULL,
  sku varchar(60) NOT NULL UNIQUE,
  barcode varchar(60),
  category_id bigint NOT NULL REFERENCES public.product_categories(id),
  uom_id bigint NOT NULL REFERENCES public.units_of_measure(id),
  unit_cost numeric(14,2) NOT NULL DEFAULT 0,
  description text,
  reorder_min_qty numeric(14,3) NOT NULL DEFAULT 0,
  reorder_max_qty numeric(14,3),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.partners (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(150) NOT NULL,
  type public.partner_type NOT NULL,
  email varchar(160),
  phone varchar(20),
  address text,
  is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE public.profiles (
  id uuid PRIMARY KEY,
  login_id varchar(60) NOT NULL UNIQUE,
  email varchar(160) NOT NULL UNIQUE,
  full_name varchar(120),
  phone varchar(20),
  warehouse_id bigint REFERENCES public.warehouses(id),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.user_roles (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  role public.app_role NOT NULL,
  UNIQUE (user_id, role)
);
CREATE TABLE public.stock_operations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference_no varchar(30) NOT NULL UNIQUE,
  operation_type public.operation_type NOT NULL,
  status public.operation_status NOT NULL DEFAULT 'DRAFT',
  warehouse_id bigint NOT NULL REFERENCES public.warehouses(id),
  source_location_id bigint REFERENCES public.locations(id),
  destination_location_id bigint REFERENCES public.locations(id),
  partner_id bigint REFERENCES public.partners(id),
  scheduled_date timestamptz NOT NULL DEFAULT now(),
  validated_date timestamptz,
  created_by uuid NOT NULL,
  responsible_user_id uuid,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.stock_operation_lines (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operation_id bigint NOT NULL REFERENCES public.stock_operations(id) ON DELETE CASCADE,
  product_id bigint NOT NULL REFERENCES public.products(id),
  uom_id bigint NOT NULL REFERENCES public.units_of_measure(id),
  quantity_planned numeric(14,3) NOT NULL DEFAULT 0,
  quantity_done numeric(14,3) NOT NULL DEFAULT 0,
  notes text
);
CREATE TABLE public.stock_adjustment_lines (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operation_id bigint NOT NULL REFERENCES public.stock_operations(id) ON DELETE CASCADE,
  product_id bigint NOT NULL REFERENCES public.products(id),
  location_id bigint NOT NULL REFERENCES public.locations(id),
  uom_id bigint NOT NULL REFERENCES public.units_of_measure(id),
  recorded_quantity numeric(14,3) NOT NULL DEFAULT 0,
  counted_quantity numeric(14,3) NOT NULL DEFAULT 0,
  difference numeric(14,3) NOT NULL DEFAULT 0
);
CREATE TABLE public.stock_quants (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES public.products(id),
  location_id bigint NOT NULL REFERENCES public.locations(id),
  quantity numeric(14,3) NOT NULL DEFAULT 0,
  reserved_quantity numeric(14,3) NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (product_id, location_id)
);
CREATE TABLE public.stock_ledger_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES public.products(id),
  location_id bigint NOT NULL REFERENCES public.locations(id),
  quantity_change numeric(14,3) NOT NULL,
  balance_after numeric(14,3) NOT NULL,
  operation_id bigint NOT NULL REFERENCES public.stock_operations(id),
  operation_type public.operation_type NOT NULL,
  reference_no varchar(30) NOT NULL,
  movement_date timestamptz NOT NULL DEFAULT now(),
  created_by uuid
);
CREATE TABLE public.operation_sequences (
  warehouse_id bigint NOT NULL REFERENCES public.warehouses(id),
  op_code varchar(5) NOT NULL,
  last_value int NOT NULL DEFAULT 0,
  PRIMARY KEY (warehouse_id, op_code)
);

