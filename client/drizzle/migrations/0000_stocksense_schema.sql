CREATE OR REPLACE FUNCTION public.protect_profile_fields() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF current_setting('app.bypass', true) = 'on' THEN RETURN NEW; END IF;
  NEW.login_id := OLD.login_id;
  NEW.email := OLD.email;
  NEW.warehouse_id := OLD.warehouse_id;
  NEW.is_active := OLD.is_active;
  NEW.updated_at := now();
  RETURN NEW;
END $$;
CREATE TRIGGER profiles_protect BEFORE UPDATE ON public.profiles FOR EACH ROW EXECUTE FUNCTION public.protect_profile_fields();

CREATE OR REPLACE FUNCTION public.handle_new_user() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_login text;
BEGIN
  v_login := COALESCE(NULLIF(NEW.raw_user_meta_data->>'login_id',''), split_part(NEW.email,'@',1));
  INSERT INTO public.profiles (id, login_id, email) VALUES (NEW.id, v_login, NEW.email);
  IF NOT EXISTS (SELECT 1 FROM public.user_roles WHERE role = 'INVENTORY_MANAGER') THEN
    INSERT INTO public.user_roles (user_id, role) VALUES (NEW.id, 'INVENTORY_MANAGER');
  ELSE
    INSERT INTO public.user_roles (user_id, role) VALUES (NEW.id, 'WAREHOUSE_STAFF');
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

